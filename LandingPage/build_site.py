#!/usr/bin/env python3
"""Make the website's images from the marketing captures.

    python3 LandingPage/build_site.py

`tools/app-store/generate.py` refreshes `LandingPage/assets/screenshots/` with every run; this
turns those captures (the raw ones: the site sets its own headlines in HTML) into the WebP
files `LandingPage/site/` serves, exports the owner-supplied mascot mark, and copies the
website's scene-based social artwork from its retained master. Run it after a screenshot run, then deploy (`LandingPage/README.md`).

Needs Pillow with WebP. The icon master is Brand/BananaAppIconMaster.png, generated by
tools/app-store/brand.py. Existing social artwork is retained in assets/brand/.
"""
from __future__ import annotations

import shutil
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
SHOTS = HERE / "assets/screenshots"
OUT = HERE / "site/assets/img"

# name on the site, source capture, width in pixels (twice the widest it is shown)
CAPTURES = [
    ("phone-plan", "iphone/raw/01-plan.png", 780),
    ("phone-routines", "iphone/raw/02-routines.png", 780),
    ("phone-nutrition", "iphone/raw/03-nutrition.png", 780),
    ("phone-workouts", "iphone/raw/05-workouts.png", 780),
    ("phone-listenmap", "iphone/raw/06-listening.png", 600),    # the pair is shown smaller,
    ("phone-transcript", "iphone/raw/07-transcripts.png", 600),  # and a map is heavy
    ("ipad-plan", "ipad/raw/01-plan.png", 1500),
    ("mac-plan", "mac/raw/01-plan.png", 1320),
    ("mac-sleep", "mac/raw/03-sleep.png", 1320),
    ("watch-workout", "watch/raw/01-workout.png", 416),
    ("watch-playing", "watch/raw/02-now-playing.png", 416),
]


def captures() -> None:
    for name, source, width in CAPTURES:
        image = Image.open(SHOTS / source).convert("RGB")
        if image.width > width:
            image = image.resize((width, round(image.height * width / image.width)), Image.LANCZOS)
        image.save(OUT / f"{name}.webp", "WEBP", quality=84, method=6)
        print(f"{name}.webp  {image.width}x{image.height}  {(OUT / f'{name}.webp').stat().st_size // 1024} KB")


def mark() -> Image.Image:
    """The owner-supplied mascot, preserving transparent corners for web marks."""
    return Image.open(ROOT / "Brand/BananaMascotReference.png").convert("RGBA")


def icons(tile: Image.Image) -> None:
    for name, size in [("apple-touch-icon.png", 180), ("favicon-48.png", 48)]:
        target = OUT.parent.parent / name
        # Touch icons use an opaque full-bleed tile; the OS supplies its corner mask.
        icon = Image.open(ROOT / "Brand/BananaAppIconMaster.png").convert("RGB")
        icon = icon.resize((size, size), Image.LANCZOS)
        icon.save(target)
    tile.resize((192, 192), Image.LANCZOS).save(OUT / "mark-192.webp", "WEBP", quality=92)


def cloud_brand() -> None:
    """Keep the production/beta cloud app's separate static assets on this same identity."""
    cloud = ROOT / "Service/public/app/assets"
    # A small embedded image keeps SVG consumers cache-compatible without shipping a
    # 1254px source raster for a 36px header mark.
    import base64, io
    tile = Image.open(ROOT / "Brand/BananaMascotReference.png").convert("RGBA").resize((192, 192), Image.LANCZOS)
    encoded = io.BytesIO(); tile.save(encoded, "PNG", optimize=True)
    svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 192 192"><image width="192" height="192" href="data:image/png;base64,' + base64.b64encode(encoded.getvalue()).decode() + '"/></svg>'
    (cloud / "mark.svg").write_text(svg)
    (HERE / "site/assets/img/banana-mark.svg").write_text(svg)
    shutil.copy2(HERE / "site/favicon-48.png", cloud / "favicon-48.png")


def social(tile: Image.Image) -> None:
    """Keep the current website scene, rather than regenerating the historical campaign."""
    shutil.copy2(HERE / "assets/brand/social-calendar-scene.png", OUT / "social.png")


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    captures()
    tile = mark()
    icons(tile)
    cloud_brand()
    social(tile)
    print("mark, icons and social.png written")
