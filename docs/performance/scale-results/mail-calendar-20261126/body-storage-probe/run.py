#!/usr/bin/env python3
"""Replay the disk-backed body representation comparison using existing Mac Release dependencies."""
import argparse
from pathlib import Path
import subprocess

SOURCE = Path(__file__).resolve().parent
ROOT = next(parent for parent in SOURCE.parents if (parent / "Banana/Model/Mail").is_dir())
ORDER = ["baseline", "design-box", "picture-box", "both-box"]
WORKLOADS = ["single", "small-thread", "long-thread", "large-html", "mixed-pictures", "image-heavy"]


def run(command, log):
    with log.open("x") as output:
        subprocess.run(command, cwd=ROOT, stdout=output, stderr=subprocess.STDOUT, check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reader-sources", type=Path, required=True,
                        help="Tests directory generated by tools/mail-reader-tests/run.py")
    parser.add_argument("--derived-data", type=Path, required=True,
                        help="Existing native Mac build with Release GRDB and SwiftSoup products")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    output = args.out.resolve()
    output.mkdir(parents=True, exist_ok=False)
    derived = args.derived_data.resolve()
    products = derived / "Build/Products/Release"
    module = derived / "SourcePackages/checkouts/GRDB.swift/Sources/GRDBSQLite"
    mail = ROOT / "Banana/Model/Mail"
    pure = ROOT / "Banana/Model/MailUI/Pure"
    sources = {path.name: path for path in sorted(mail.glob("*.swift"))}
    for path in sorted(args.reader_sources.resolve().glob("*.swift")):
        if not path.name.endswith("Tests.swift") and path.name != "MailToastExtract.swift":
            sources[path.name] = path
    for name in ("MailReaderModel", "MailConversationFacts", "MailMessageDisplay", "MailRowDisplay",
                 "MailPlainText", "MailToastText", "MailActions", "MailVerificationCode"):
        sources[name + ".swift"] = pure / (name + ".swift")
    sources["LiveFilter.swift"] = ROOT / "Banana/Model/LiveFilter.swift"
    styled = output / "MailAttributedText.swift"
    styled.write_text("import SwiftUI\n" + (pure / styled.name).read_text())
    sources[styled.name] = styled
    original = (mail / "MailContract.swift").read_text()
    for variant in ORDER:
        directory = output / variant
        directory.mkdir()
        source = original
        for flag, declaration in [("design-box", "case designed(document:"), ("picture-box", "case picture(MailPicture)")]:
            if variant in (flag, "both-box"):
                if source.count(declaration) != 1:
                    raise ValueError(f"Expected exactly one declaration for {flag}")
                source = source.replace(declaration, "indirect " + declaration)
        contract = directory / "MailContract.swift"
        contract.write_text(source)
        sources[contract.name] = contract
        command = [ROOT / "tools/agents/xcode-lock.sh", "-l", "build", "swiftc", "-O",
                   "-whole-module-optimization", "-parse-as-library", "-target", "arm64-apple-macos14.0",
                   "-I", products, "-I", module, *sources.values(), SOURCE / "main.swift",
                   products / "GRDB.o", products / "SwiftSoup.o", "-lsqlite3", "-o", directory / "bench"]
        run(command, output / f"compile-{variant}.log")
    database = output / "database"
    run([output / "baseline/bench", "seed", database], output / "seed.log")
    for index, variant in enumerate(ORDER + ORDER[::-1], 1):
        for workload in WORKLOADS:
            program = output / variant / "bench"
            run([program, "read", database, workload], output / f"{index}-{variant}-{workload}.jsonl")
            if workload in ("large-html", "mixed-pictures", "image-heavy"):
                run([program, "evict", database, workload], output / f"{index}-{variant}-{workload}-eviction.jsonl")


if __name__ == "__main__":
    main()
